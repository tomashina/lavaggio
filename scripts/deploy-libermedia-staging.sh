#!/bin/bash
set -Eeuo pipefail
umask 022
source_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
target_root=/home/amds/libermedia.agmedia.rocks
php_bin=/opt/cpanel/ea-php84/root/usr/bin/php
[[ "$source_root" == /home/amds/repositories/libermedia-new ]] || { echo 'Unexpected source directory'; exit 1; }
[[ -f "$target_root/.env" ]] || { echo 'Configure the staging environment before deployment'; exit 1; }
[[ -f "$source_root/public/build/manifest.json" ]] || { echo 'Missing frontend build'; exit 1; }
mkdir -p /home/amds/.libermedia-backups
backup_root="/home/amds/.libermedia-backups/$(date +%Y%m%d-%H%M%S)"
mkdir -p "$backup_root"
# Preserve the domain-specific PHP handler generated by cPanel.
handler_file="$backup_root/php-handler"
if [[ -f "$target_root/public/.htaccess" ]]; then
    awk '/# php -- BEGIN cPanel-generated handler/{capture=1} capture{print} /# php -- END cPanel-generated handler/{capture=0}' "$target_root/public/.htaccess" > "$handler_file"
fi
rsync -a --chmod=D755,F644 --backup --backup-dir="$backup_root" --exclude=.git --exclude=.env --exclude=vendor --exclude=node_modules --exclude=storage --exclude=public/storage --exclude=public/image --exclude=bootstrap/cache --exclude=database/database.sqlite "$source_root/" "$target_root/"
if [[ -s "$handler_file" ]]; then
    cat "$handler_file" >> "$target_root/public/.htaccess"
fi
chmod 755 "$target_root"
cd "$target_root"
mkdir -p storage/framework/{cache/data,sessions,views} storage/logs storage/app/public bootstrap/cache
"$php_bin" /home/amds/bin/composer install --no-dev --prefer-dist --no-interaction --optimize-autoloader
"$php_bin" artisan migrate --force
[[ -L public/storage ]] || "$php_bin" artisan storage:link
"$php_bin" artisan optimize:clear
"$php_bin" artisan config:cache
"$php_bin" artisan view:cache
printf '%s\n' "Deployed $(git -C "$source_root" rev-parse HEAD)"
